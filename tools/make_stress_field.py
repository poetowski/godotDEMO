"""Writes src/world/stress/stress_field.tscn: the field scene with its sector
designs replaced by one StressWoods design in every one of the 400 sectors.
Run it again after changing field.tscn's environment, terrain, grid,
streamer, player or HUD: python tools/make_stress_field.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
LETTERS = "ABCDEFGHIJKLMNOPQRST"

field = (ROOT / "src/world/field/field.tscn").read_text(encoding="utf-8")
# Godot's ids would clash with the field's own; Godot adds new ones on save.
field = re.sub(r' uid="uid://[a-z0-9]+"', "", field)
field = re.sub(r" unique_id=\d+", "", field)

blocks = field.split("\n\n")
kept = []
for block in blocks:
    # The stress world is one region of designs: no streamed ground or woods.
    if block.startswith('[node name="Vegetation"'):
        continue
    block = block.replace("chunked = true\n", "")
    if '/sectors/' in block and block.startswith("[ext_resource"):
        lines = [line for line in block.split("\n") if "/sectors/" not in line]
        block = "\n".join(lines)
    if block.startswith('[node name=') and 'parent="Sectors"' in block:
        continue
    kept.append(block)
scene = "\n\n".join(kept)
scene = scene.replace(
    '[ext_resource type="Script" path="res://src/world/field/field.gd" id="1_field"]',
    '[ext_resource type="Script" path="res://src/world/stress/stress_field.gd" id="1_field"]\n'
    '[ext_resource type="Script" path="res://src/world/stress/stress_woods.gd" id="20_woods"]',
)
scene = scene.replace(
    'editor_description = "Grass everywhere with a 20 x 20 grid of 10 m sectors. A1 is the south-west corner sector and the start; letters grow east, numbers north. Sector designs live under Sectors."',
    'editor_description = "Stress test: every sector filled with woodland on Perlin hills. Generated by tools/make_stress_field.py; not game content."',
)
designs = []
for row in range(1, 21):
    for column, letter in enumerate(LETTERS):
        designs.append(
            f'[node name="Stress{letter}{row}" type="Node3D" parent="Sectors"]\n'
            f'script = ExtResource("20_woods")\n'
            f'sectors = PackedStringArray("{letter}{row}")\n'
            f'design_id = "stress_{letter.lower()}{row}"\n'
            f"design_seed = {row * 100 + column}"
        )
# Dense woodland everywhere: keep full detail close, far models beyond.
scene = scene.replace('focus = NodePath("../Player")', 'focus = NodePath("../Player")\nload_radius = 2\nunload_radius = 3')
marker = '[node name="Terrain"'
index = scene.index(marker)
scene = scene[:index] + "\n\n".join(designs) + "\n\n" + scene[index:]
(ROOT / "src/world/stress/stress_field.tscn").write_text(scene, encoding="utf-8", newline="\n")
print(f"wrote {len(designs)} designs")

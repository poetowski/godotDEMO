"""Writes src/world/big/big_world.tscn: the field scene without its sector
designs, its ground streamed in chunks (TerrainChunks), woods growing on
their own (Vegetation), and the grid, clouds and streaming following the
player. Run it again after changing field.tscn:
python tools/make_big_world.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent

field = (ROOT / "src/world/field/field.tscn").read_text(encoding="utf-8")
field = re.sub(r' uid="uid://[a-z0-9]+"', "", field)
field = re.sub(r" unique_id=\d+", "", field)

kept = []
for block in field.split("\n\n"):
    if "/sectors/" in block and block.startswith("[ext_resource"):
        block = "\n".join(line for line in block.split("\n") if "/sectors/" not in line)
    if block.startswith("[node name=") and 'parent="Sectors"' in block:
        continue
    kept.append(block)
scene = "\n\n".join(kept)
scene = scene.replace(
    '[ext_resource type="Script" path="res://src/world/field/field.gd" id="1_field"]',
    '[ext_resource type="Script" path="res://src/world/big/big_world.gd" id="1_field"]\n'
    '[ext_resource type="Script" path="res://src/world/nature/vegetation.gd" id="40_vegetation"]',
)
scene = re.sub(r'editor_description = "Grass everywhere[^"]*"',
               'editor_description = "Big world: 10 x 10 regions (R1 to R100, 2 km) of hilly woodland, ground and woods streamed around the player. Generated by tools/make_big_world.py; not game content."',
               scene)


def set_props(scene, header_start, props, paths):
    start = scene.index(header_start)
    end = scene.index("\n", start)
    header = scene[start:end]
    if paths:
        if "node_paths=" in header:
            header = re.sub(r'node_paths=PackedStringArray\(([^)]*)\)',
                            lambda m: "node_paths=PackedStringArray(%s, %s)" % (m.group(1), ", ".join('"%s"' % p for p in paths)), header)
        else:
            header = header[:-1] + " node_paths=PackedStringArray(%s)]" % ", ".join('"%s"' % p for p in paths)
    block_end = scene.find("\n\n", end)
    lines = scene[end:block_end].split("\n")
    # Properties go after the script line, or Godot drops them as unknown.
    at = next((k for k, line in enumerate(lines) if line.startswith("script = ")), len(lines) - 1)
    lines[at + 1:at + 1] = props
    return scene[:start] + header + "\n".join(lines) + scene[block_end:]


scene = set_props(scene, '[node name="Terrain"', ["chunked = true", 'focus = NodePath("../Player")'], ["focus"])
scene = set_props(scene, '[node name="SectorGrid"', ['focus = NodePath("../Player")'], ["focus"])
scene = set_props(scene, '[node name="Clouds"', ['follow = NodePath("../Player")'], ["follow"])
vegetation = (
    '[node name="Vegetation" type="Node3D" parent="." node_paths=PackedStringArray("focus", "terrain")]\n'
    'script = ExtResource("40_vegetation")\n'
    'focus = NodePath("../Player")\n'
    'terrain = NodePath("../Terrain")\n\n'
)
marker = '[node name="Player"'
index = scene.index(marker)
scene = scene[:index] + vegetation + scene[index:]
scene = scene.replace('[node name="Field" type="Node3D"]', '[node name="BigWorld" type="Node3D"]', 1)
(ROOT / "src/world/big/big_world.tscn").write_text(scene, encoding="utf-8", newline="\n")
print("wrote big_world.tscn")
